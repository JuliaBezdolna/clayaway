// ClayArena · offline packs (PWA step 3, 11.11.2026): the lists of files that «Зберегти для офлайну» saves on the device, one per
// product and language. Written to docs/offline/<product>-<lang>.json; read by docs/shared/offline-pack.js (the button on the
// glossary home and the Academy home), which downloads the files into the cache "clayarena-pack-<product>-<lang>" that the
// service worker docs/sw.js serves when there is no network.
//   glossary-<l>  the glossary home and every term page of that language (<l>/glossary/, uk: glossary/), and the files they load
//   academy-<l>   every Academy page of that language (<l>/learn/, uk: learn/), its data (learn/data/<l>/**, id-map, languages) and
//                 what the app loads on demand (glossary data and rules trainer bank for the cards and games, sims texts)
// Left out on purpose: redirect stubs (meta refresh), the recorded English voice of the glossary (glossary/audio/*.mp3, 3.1 MB: offline
// docs/shared/speak.js falls back to the device voice) and the 3D blocks (docs/shared/3d/, 17 MB, made in ClayArenaPromo).
// Each list: { product, lang, v, files: [paths from the site root], bytes, gz } — v changes with the content of any file (the button then
// offers an update), gz = the sum of the files gzipped one by one ≈ what the download costs (GitHub Pages sends them compressed).
// Called at the very end of scripts/build_seo.mjs (after the 3D blocks are written into the pages); alone: bun scripts/build_offline.mjs
import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync, statSync } from "fs";
import { createHash } from "crypto";
import { gzipSync } from "zlib";

const LANGS = ["en", "uk", "de", "fr", "it", "cs", "pl", "pt", "hu", "fi", "lt"];
const ASSET = /\.(js|css|json|png|svg|webp|jpe?g|ico|woff2?)$/i;
const SKIP = [/^shared\/3d\//, /^glossary\/audio\//, /^og\/(?!favicon\.png|apple-touch-icon\.png)/];

function pages(dir, root, skipDirs) {
  const out = [];
  const walk = d => { for (const e of readdirSync(d, { withFileTypes: true })) { const p = `${d}/${e.name}`;
    if (e.isDirectory()) { if (!skipDirs.includes(p.slice(root.length + 1))) walk(p); } else if (e.name === "index.html") out.push(p.slice(root.length + 1)); } };
  if (existsSync(`${root}/${dir}`)) walk(`${root}/${dir}`);
  return out;
}
// the local files a page loads itself: <script src>, <link href> (stylesheet, icon), <img src>, data-src (audio is skipped below)
function assets(root, page, html) {
  const out = new Set(), here = page.replace(/[^/]*$/, "");
  for (const m of html.matchAll(/<(?:script|img|source)\b[^>]*?\ssrc="([^"#?]+)|<link\b[^>]*?\shref="([^"#?]+)"/gi)) {
    const ref = m[1] || m[2]; if (!ref || /^(?:[a-z]+:|\/\/|data:)/i.test(ref) || !ASSET.test(ref)) continue;
    const abs = new URL(ref, "https://x/" + here).pathname.slice(1);
    if (existsSync(`${root}/${abs}`)) out.add(abs);
  }
  return out;
}

export function buildOffline({ docs = "docs", quiet = false } = {}) {
  mkdirSync(`${docs}/offline`, { recursive: true });
  const report = [];
  for (const lang of LANGS) {
    const pre = lang === "uk" ? "" : `${lang}/`;
    const defs = {
      glossary: { dirs: [`${pre}glossary`], skip: [`${pre}glossary/data`, `${pre}glossary/audio`], extra: [] },
      academy: { dirs: [`${pre}learn`], skip: [`${pre}learn/data`, `${pre}learn/app`],
        extra: [...(existsSync(`${docs}/learn/data/${lang}`) ? walkFiles(docs, `learn/data/${lang}`) : []), "learn/data/id-map.json", "learn/data/languages.json",
          "glossary/data/glossary.js", "glossary/data/learn_terms.js", `glossary/data/i18n/${lang}.js`, "shared/terms.js",
          "shared/sims-text.js", `shared/sims-text-${lang}.js`, "shared/sims.min.js", "rules/data/quiz-sporting.js", "rules/data/quiz-compak.js",
          `rules/data/i18n/quiz-${lang}.json`] }
    };
    for (const [product, d] of Object.entries(defs)) {
      const files = new Set();
      for (const dir of d.dirs) for (const p of pages(dir, docs, d.skip)) {
        const html = readFileSync(`${docs}/${p}`, "utf8");
        if (/http-equiv="refresh"/i.test(html)) continue; // a redirect stub of a merged id
        files.add(p.replace(/index\.html$/, "")); // saved under the address the visitor opens (…/zero/), not …/index.html
        for (const a of assets(docs, p, html)) files.add(a);
      }
      for (const x of d.extra) if (existsSync(`${docs}/${x}`)) files.add(x);
      const list = [...files].filter(f => !SKIP.some(r => r.test(f))).sort();
      const h = createHash("sha1"); let bytes = 0, gz = 0;
      for (const f of list) { const b = readFileSync(`${docs}/${f.endsWith("/") || f === "" ? f + "index.html" : f}`); h.update(f + "\0"); h.update(b); bytes += b.length; gz += gzipSync(b, { level: 6 }).length; }
      const out = { _note: "GENERATED by scripts/build_offline.mjs — what «Зберегти для офлайну» saves (docs/shared/offline-pack.js); do not edit.",
        product, lang, v: h.digest("hex").slice(0, 12), count: list.length, bytes, gz, files: list };
      writeFileSync(`${docs}/offline/${product}-${lang}.json`, JSON.stringify(out));
      report.push(`${product}-${lang} ${list.length} files ${(gz / 1048576).toFixed(1)} MB`);
    }
  }
  if (!quiet) console.log("offline packs: " + report.join(" · "));
  return report;
}
function walkFiles(docs, dir) {
  const out = []; const walk = d => { for (const e of readdirSync(`${docs}/${d}`, { withFileTypes: true })) { const p = `${d}/${e.name}`; if (e.isDirectory()) walk(p); else out.push(p); } };
  walk(dir); return out;
}
if (import.meta.main || (process.argv[1] || "").endsWith("build_offline.mjs")) buildOffline();
