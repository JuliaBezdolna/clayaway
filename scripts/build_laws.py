"""Turn docs/learn/data/laws-<cc>.json into laws-<cc>.js (window.LAWS[cc]) for the Academy app and the static build.

Two JSON shapes are supported:
  - by state (Germany): {as_of, note_uk/en, states:[{state_uk, state_en, state_de, law, article, rule_uk/en, since, url, verified}]}
  - by country:         {as_of, country_uk/en, note_uk/en, lead:[{scope_uk/en, law, article, rule_uk/en, since, url, verified}],
                         travel:[{topic_uk/en, law, article, rule_uk/en, url, verified}]}
Lessons reference tables with `law_tables: [{code: "de"|"fr"|..., part: "states"|"lead"|"travel"}]`.
Run: python scripts/build_laws.py   (then bun scripts/build_seo.mjs)
"""
import glob, json, os
from pathlib import Path

D = Path(__file__).resolve().parent.parent / "docs" / "learn" / "data"
for f in sorted(glob.glob(str(D / "laws-*.json"))):
    code = Path(f).stem.split("-", 1)[1]
    data = json.load(open(f, encoding="utf-8"))
    (D / f"laws-{code}.js").write_text(
        f"/* Generated by scripts/build_laws.py from laws-{code}.json — edit the JSON, then re-run. */\n"
        f"window.LAWS = window.LAWS || {{}};\nwindow.LAWS[{json.dumps(code)}] = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n",
        encoding="utf-8")
    print("ok", code)
