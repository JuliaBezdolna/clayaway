"""RETIRED (10.2026): replaced by scripts/build_academy.mjs (one "Академія ClayArena", content in content/academy/).
Kept only as a reference until the switch-over release; scripts/build_seo.mjs does not use it. Running it would overwrite
docs/interpreter/ and docs/shared/sims-text.js (now generated by build_academy.mjs), so it refuses to run without --legacy.

Build ClayArena Interpreter Academy data (docs/interpreter/).

Sources (in the repo, edit these):
  archive/legacy-docs/interpreter/src/missions/<mission>.json  master content, every text field {"en": ..., "uk": ...}
  archive/legacy-docs/interpreter/src/ui.json                  interface strings {"key": {"en": ..., "uk": ...}}
  Terms come from the ONE ClayArena glossary (no copy in this project):
    docs/glossary/data/glossary.js (rules terms) + learn_terms.js (Academy + Interpreter Academy terms) + i18n/<lang>.js (local forms, definitions)
  archive/legacy-docs/interpreter/src/i18n/<lang>.json         translations for the other languages (same ids):
        {"ui": {key: text}, "missions": {mid: {"title", "intro", "lessons": {lid: {"title", "body": [],
         "key_points": [], "coach_says": [{"meaning", "say"}], "quiz": [{"q", "options": [], "why"}]}}}}}
Output (generated, do not edit):
  archive/legacy-docs/interpreter/data/<lang>.js  window.IA = {lang, ui, missions}   — one file per ClayArena language, English fallback per field
  archive/legacy-docs/interpreter/data/terms.js   window.IA_TERMS = {langs, terms}

In production the same structure maps to ClayArena CMS entities: Mission, Lesson (translatable fields), CoachPhrase, QuizItem, Term.
Run: python scripts/build_interpreter.py
"""
import json, re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
D = ROOT / "docs" / "interpreter"
# The sources (src/) and the generated data (data/) were moved out of docs/ to archive/legacy-docs/interpreter/ on 08.10.2026
# (not published any more; owner decision: the site names no other clay discipline, these files still did).
A = ROOT / "archive" / "legacy-docs" / "interpreter"
LANGS = ["en", "uk", "de", "fr", "it", "cs", "pl", "pt", "hu", "fi", "lt"]  # ClayArena site languages only
ORDER = ["sport", "gear", "targets", "flight", "basics", "lead", "faults", "sporting", "compak", "referee", "etiquette", "interpreter"]


def rules_titles():
    """Rule item id -> {en, uk} titles, read from the FITASC paraphrase data (used as link labels)."""
    out = {}
    for book in ("sporting", "compak"):
        s = (ROOT / "docs" / "rules" / "data" / f"{book}.js").read_text(encoding="utf-8")
        data = json.loads(re.search(r"window\.RULES\.push\((.*)\);\s*$", s, re.S).group(1))
        for sec in data["sections"]:
            for it in sec["items"]:
                out[(book, it["id"])] = {"en": f'{sec["chapter"]} · {it["title_en"]}', "uk": f'{sec["chapter"]} · {it["title_uk"]}'}
    # FITASC age categories (docs/rules/data/categories.js) — referenced as {"book": "categories", "id": "junior"}
    s = (ROOT / "docs" / "rules" / "data" / "categories.js").read_text(encoding="utf-8")
    cats = json.loads(re.search(r"window\.FITASC_CATEGORIES\s*=\s*(\{.*\})\s*;?\s*$", s, re.S).group(1))
    for c in cats["categories"]:
        out[("categories", c["id"])] = {"en": c["name_en"], "uk": c.get("name_uk", c["name_en"])}
    return out


def _js(p):
    s = p.read_text(encoding="utf-8")
    return json.loads(re.search(r"=\s*(\{.*\})\s*;?\s*$", s, re.S).group(1))


def glossary_terms():
    """Read the ClayArena glossary (single term store) -> {langs, terms:[{id, en, aka, group, def:{lang}, tr:{lang:{term, alt, note, conf}}, page:{lang:url}}]}."""
    G = ROOT / "docs" / "glossary" / "data"
    by = {}
    for f in ("glossary.js", "learn_terms.js"):
        for t in _js(G / f)["terms"]:
            by.setdefault(t["id"], {}).update(t)
    I = {l: _js(G / "i18n" / f"{l}.js")["terms"] for l in LANGS if (G / "i18n" / f"{l}.js").exists()}
    out = []
    for tid, t in by.items():
        d = {"en": t.get("short_en", ""), "uk": t.get("short_uk", "")}
        tr, page = {}, {"uk": f"../glossary/{tid}/", "en": f"../en/glossary/{tid}/"}
        for l, terms in I.items():
            x = terms.get(tid)
            if not x: continue
            if x.get("short") and l != "uk": d[l] = x["short"]; page[l] = f"../{l}/glossary/{tid}/"
            if x.get("term_local"): tr[l] = {k: x[k] for k in ("term_local", "alt", "note", "conf") if x.get(k)}; tr[l]["term"] = tr[l].pop("term_local")
        out.append({"id": tid, "en": t["term"], "aka": t.get("aka", []), "group": t.get("cat", ""), "def": {k: v for k, v in d.items() if v}, "tr": tr, "page": page})
    return {"langs": LANGS, "terms": out}


def pick(v, lang, tr=None):
    """Text in `lang`: master {en, uk} field, else translation `tr`, else English."""
    if isinstance(v, dict):
        return v.get(lang) if v.get(lang) not in (None, "", []) else (tr if tr not in (None, "", []) else v.get("en"))
    return v


def main():
    RT = rules_titles()
    ui = json.loads((A / "src" / "ui.json").read_text(encoding="utf-8"))
    terms = glossary_terms()
    missions = {}
    for f in sorted((A / "src" / "missions").glob("*.json")):
        m = json.loads(f.read_text(encoding="utf-8")); missions[m["id"]] = m
    ms = [missions[k] for k in ORDER if k in missions] + [m for k, m in missions.items() if k not in ORDER]
    i18n = {}
    for l in LANGS:
        p = A / "src" / "i18n" / f"{l}.json"
        i18n[l] = json.loads(p.read_text(encoding="utf-8")) if p.exists() else {}
    (A / "data").mkdir(exist_ok=True)
    report, per_lang = {}, {}
    for l in LANGS:
        T = i18n[l]; TM = T.get("missions", {}); miss = 0
        out_ms = []
        for m in ms:
            tm = TM.get(m["id"], {}); tl = tm.get("lessons", {})
            lessons = []
            for les in m["lessons"]:
                x = tl.get(les["id"], {})
                if l not in ("en", "uk") and not x: miss += 1
                cs = []
                for k, c in enumerate(les.get("coach_says", [])):
                    xc = (x.get("coach_says") or [{}] * 99)[k] if k < len(x.get("coach_says") or []) else {}
                    say = c.get("say", {}) if isinstance(c.get("say"), dict) else {}
                    cs.append({"en": c["en"], "meaning": pick(c.get("meaning", {}), l, xc.get("meaning")),
                               "say": None if l == "en" else (say.get(l) or xc.get("say"))})
                qz = []
                for k, q in enumerate(les.get("quiz", [])):
                    xq = (x.get("quiz") or [])[k] if k < len(x.get("quiz") or []) else {}
                    qz.append({"q": pick(q["q"], l, xq.get("q")), "options": pick(q["options"], l, xq.get("options")),
                               "answer": q["answer"], "why": pick(q.get("why", {}), l, xq.get("why"))})
                lessons.append({"id": les["id"], "minutes": les.get("minutes", 5), "title": pick(les["title"], l, x.get("title")),
                                "body": pick(les["body"], l, x.get("body")), "key_points": pick(les.get("key_points", {}), l, x.get("key_points")) or [],
                                "terms": les.get("terms", []), "sources": les.get("sources", []), "sim": les.get("sim"),
                                "rule_refs": [dict(r, label=RT.get((r["book"], r["id"]), {}).get("uk" if l == "uk" else "en", r["id"]))
                                              for r in les.get("rule_refs", []) if (r["book"], r["id"]) in RT],
                                "coach_says": cs, "quiz": qz})
            out_ms.append({"id": m["id"], "icon": m.get("icon", ""), "title": pick(m["title"], l, tm.get("title")),
                           "intro": pick(m.get("intro", {}), l, tm.get("intro")), "lessons": lessons})
        u = {k: pick(v, l, T.get("ui", {}).get(k)) for k, v in ui.items()}
        (A / "data" / f"{l}.js").write_text(
            f"/* Generated by scripts/build_interpreter.py — do not edit; edit archive/legacy-docs/interpreter/src/. Language: {l} */\n"
            f"window.IA = " + json.dumps({"lang": l, "ui": u, "missions": out_ms}, ensure_ascii=False) + ";\n", encoding="utf-8")
        report[l] = miss; per_lang[l] = {"ui": u, "missions": out_ms}
    # keep only terms the course uses (lesson "terms"), so data/terms.js stays small
    used = {tid for m in ms for les in m["lessons"] for tid in les.get("terms", [])}
    missing = sorted(used - {t["id"] for t in terms["terms"]})
    if missing: print("WARNING: terms used by lessons but missing in the glossary:", missing)
    terms["terms"] = [t for t in terms["terms"] if t["id"] in used]
    (A / "data" / "terms.js").write_text("/* Generated by scripts/build_interpreter.py — do not edit. */\nwindow.IA_TERMS = "
                                         + json.dumps(terms, ensure_ascii=False) + ";\n", encoding="utf-8")
    # texts of the shared simulations (docs/shared/sims.js) for pages outside the course (glossary, rules trainer)
    SIM_KEYS = ["launch", "method", "m_maintained", "m_swing", "m_pullaway", "m_ambush", "speed", "distance", "demo", "try", "shoot", "hit", "behind", "ahead",
                "perceived", "actual", "lab_note", "decision", "shot_moment", "lead_word", "unit_m", "unit_ft", "unit_ms", "pair_report", "pair_sim", "pair_rafale", "listen"]
    st = {l: {k: pick(ui[k], l, i18n[l].get("ui", {}).get(k)) for k in SIM_KEYS if k in ui} for l in LANGS}
    head = "/* Generated by scripts/build_interpreter.py from archive/legacy-docs/interpreter/src/ui.json (+ i18n) — texts of docs/shared/sims.js. */"
    (ROOT / "docs" / "shared" / "sims-text.js").write_text(head + "\nwindow.CLAYSIMS_TEXT = " + json.dumps(st, ensure_ascii=False) + ";\n", encoding="utf-8")
    n = sum(len(m["lessons"]) for m in ms)
    from build_interpreter_pages import build as build_pages  # static indexable pages (SEO/GEO)
    done_langs = [l for l in LANGS if report[l] == 0]  # a language gets static pages only when fully translated
    pages = build_pages(per_lang, terms, done_langs)
    print(f"missions {len(ms)}, lessons {n}, terms {len(terms['terms'])}; untranslated lessons per lang: {report}; static pages {len(pages)}")


if __name__ == "__main__":
    import sys
    if "--legacy" not in sys.argv:
        sys.exit("RETIRED: use bun scripts/build_seo.mjs (the Academy build is scripts/build_academy.mjs). See the docstring.")
    main()
